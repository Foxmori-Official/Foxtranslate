// @vitest-environment jsdom
import { afterEach, expect, it, vi } from 'vitest'
import { isTrustedInteraction, protectExtensionUi } from '../../src/shared/trustedEvents'
import { initSelection } from '../../src/content/selection'
import { initInput } from '../../src/content/input'
import { DEFAULT_CONFIG } from '../../src/shared/config'
import { DEFAULT_PAGE_CONFIG } from '../../src/shared/pageConfig'

afterEach(() => { document.body.replaceChildren(); vi.useRealTimers(); vi.unstubAllGlobals() })

it('blocks programmatic controls inside extension UI', () => {
  const root = document.createElement('div')
  const button = document.createElement('button')
  root.append(button)
  document.body.append(root)
  protectExtensionUi(root)
  const run = vi.fn()
  button.addEventListener('click', run)
  button.addEventListener('change', run)
  button.click()
  button.dispatchEvent(new Event('change', { bubbles: true }))
  expect(isTrustedInteraction(new Event('click'))).toBe(false)
  expect(run).not.toHaveBeenCalled()
})

it('blocks trusted change events generated by a noncancelable synthetic checkbox click', () => {
  const root = document.createElement('div')
  const checkbox = document.createElement('input')
  checkbox.type = 'checkbox'
  root.append(checkbox)
  document.body.append(root)
  protectExtensionUi(root)
  const enable = vi.fn()
  checkbox.addEventListener('change', enable)
  checkbox.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: false }))
  expect(enable).not.toHaveBeenCalled()
})

it('does not translate script-created selections or hidden input synthetic shortcuts', async () => {
  vi.useFakeTimers()
  const sendMessage = vi.fn()
  vi.stubGlobal('chrome', { runtime: { sendMessage } })
  const paragraph = document.createElement('p')
  paragraph.textContent = 'An untrusted automatic selection'
  const input = document.createElement('textarea')
  input.hidden = true
  input.value = 'synthetic input'
  document.body.append(paragraph, input)
  initSelection(structuredClone(DEFAULT_PAGE_CONFIG))
  initInput(structuredClone(DEFAULT_CONFIG))
  window.getSelection()!.selectAllChildren(paragraph)
  document.dispatchEvent(new Event('selectionchange'))
  paragraph.dispatchEvent(new MouseEvent('pointerup', { button: 0, bubbles: true }))
  input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', altKey: true, bubbles: true }))
  await vi.advanceTimersByTimeAsync(300)
  expect(sendMessage).not.toHaveBeenCalled()
  expect(document.querySelector('.tv-sel-popup')).toBeNull()
})
